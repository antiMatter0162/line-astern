  function measureLine(text, pixelSize) {
    if (text.length === 0) return 0;
    return ((text.length - 1) * 6 + 5) * pixelSize;
  }

  function create(scene, text, options = {}) {
    let currentText = text;
    let currentColor = options.color ?? 0xffffff;
    const pixelSize = options.pixelSize ?? 2;
    const align = options.align ?? "left";
    let anchorX = options.x ?? 0;
    let anchorY = options.y ?? 0;
    const graphics = scene.add.graphics().setDepth(options.depth ?? 0);

    function redraw() {
      const lines = String(currentText).toUpperCase().split("\n");
      const maximumWidth = Math.max(0, ...lines.map((line) => measureLine(line, pixelSize)));
      const left = align === "center" ? anchorX - maximumWidth / 2
        : align === "right" ? anchorX - maximumWidth : anchorX;
      graphics.setPosition(left, anchorY).clear().fillStyle(currentColor, 1);
      lines.forEach((line, lineIndex) => {
        const lineWidth = measureLine(line, pixelSize);
        const lineOffset = align === "center" ? (maximumWidth - lineWidth) / 2
          : align === "right" ? maximumWidth - lineWidth : 0;
        [...line].forEach((character, characterIndex) => {
          const glyph = glyphs[character];
          if (!glyph) return;
          glyph.forEach((row, glyphY) => {
            [...row].forEach((pixel, glyphX) => {
              if (pixel !== "1") return;
              graphics.fillRect(
                lineOffset + (characterIndex * 6 + glyphX) * pixelSize,
                (lineIndex * 9 + glyphY) * pixelSize,
                pixelSize,
                pixelSize,
              );
            });
          });
        });
      });
    }

    graphics.setPixelText = (nextText) => {
      currentText = nextText;
      redraw();
      return graphics;
    };
    graphics.setPixelColor = (nextColor) => {
      currentColor = nextColor;
      redraw();
      return graphics;
    };
    graphics.setPixelPosition = (nextX, nextY) => {
      anchorX = nextX;
      anchorY = nextY;
      redraw();
      return graphics;
    };
    redraw();
    return graphics;
  }

  return { create, measureLine };
